    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
       String petId = txtPetID.getText().trim();
String treatmentDate = txtTreatmentDate.getText().trim();
String description = txtDescription.getText().trim();
String medication = txtMedication.getText().trim();
String costText = txtCost.getText().trim();

if (petId.isEmpty() || treatmentDate.isEmpty()
        || description.isEmpty() || medication.isEmpty()
        || costText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Please fill all fields.");
    return;
}

try {
    int petIdValue = Integer.parseInt(petId);
    java.sql.Date dateValue =
            java.sql.Date.valueOf(treatmentDate);
    double costValue =
            Double.parseDouble(costText);

    String sql = "INSERT INTO treatments "
            + "(pet_id, treatment_date, description, medication, cost) "
            + "VALUES (?, ?, ?, ?, ?)";

    try (java.sql.Connection con =
            util.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst =
            con.prepareStatement(sql)) {

        pst.setInt(1, petIdValue);
        pst.setDate(2, dateValue);
        pst.setString(3, description);
        pst.setString(4, medication);
        pst.setDouble(5, costValue);

        if (pst.executeUpdate() > 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Treatment added successfully!");

            txtTreatmentID.setText("");
            txtPetID.setText("");
            txtTreatmentDate.setText("");
            txtDescription.setText("");
            txtMedication.setText("");
            txtCost.setText("");
        }
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Pet ID must be a number and Cost must be a number.");

} catch (IllegalArgumentException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Date must be in YYYY-MM-DD format.");

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String treatmentId = txtTreatmentID.getText().trim();
String petId = txtPetID.getText().trim();
String treatmentDate = txtTreatmentDate.getText().trim();
String description = txtDescription.getText().trim();
String medication = txtMedication.getText().trim();
String costText = txtCost.getText().trim();

if (treatmentId.isEmpty() || petId.isEmpty()
        || treatmentDate.isEmpty() || description.isEmpty()
        || medication.isEmpty() || costText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Please fill all fields.");
    return;
}

try {
    int treatmentIdValue = Integer.parseInt(treatmentId);
    int petIdValue = Integer.parseInt(petId);
    java.sql.Date dateValue =
            java.sql.Date.valueOf(treatmentDate);
    double costValue =
            Double.parseDouble(costText);

    String sql = "UPDATE treatments SET "
            + "pet_id=?, treatment_date=?, description=?, "
            + "medication=?, cost=? WHERE treatment_id=?";

    try (java.sql.Connection con =
            util.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst =
            con.prepareStatement(sql)) {

        pst.setInt(1, petIdValue);
        pst.setDate(2, dateValue);
        pst.setString(3, description);
        pst.setString(4, medication);
        pst.setDouble(5, costValue);
        pst.setInt(6, treatmentIdValue);

        if (pst.executeUpdate() > 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Treatment updated successfully!");

            txtTreatmentID.setText("");
            txtPetID.setText("");
            txtTreatmentDate.setText("");
            txtDescription.setText("");
            txtMedication.setText("");
            txtCost.setText("");

        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Treatment ID not found.");
        }
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Treatment ID, Pet ID and Cost must be numbers.");

} catch (IllegalArgumentException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Date must be in YYYY-MM-DD format.");

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
     String treatmentId = txtTreatmentID.getText().trim();

if (treatmentId.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Please enter Treatment ID.");
    return;
}

int confirm = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this treatment?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirm != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

try {
    int treatmentIdValue = Integer.parseInt(treatmentId);

    String sql = "DELETE FROM treatments WHERE treatment_id=?";

    try (java.sql.Connection con =
            util.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst =
            con.prepareStatement(sql)) {

        pst.setInt(1, treatmentIdValue);

        if (pst.executeUpdate() > 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Treatment deleted successfully!");

            txtTreatmentID.setText("");
            txtPetID.setText("");
            txtTreatmentDate.setText("");
            txtDescription.setText("");
            txtMedication.setText("");
            txtCost.setText("");

        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Treatment ID not found.");
        }
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Treatment ID must be a number.");

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnDeleteActionPerformed

