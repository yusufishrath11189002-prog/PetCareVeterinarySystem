    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String customerId = txtCustomerID.getText().trim();
String petName = txtPetName.getText().trim();
String species = txtSpecies.getText().trim();
String breed = txtBreed.getText().trim();
String ageText = txtAge.getText().trim();

if (customerId.isEmpty() || petName.isEmpty() || species.isEmpty()
        || breed.isEmpty() || ageText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Please fill all fields.");
    return;
}

try {
    int customerIdValue = Integer.parseInt(customerId);
    int ageValue = Integer.parseInt(ageText);

    String sql = "INSERT INTO pets "
            + "(customer_id, pet_name, species, breed, age) "
            + "VALUES (?, ?, ?, ?, ?)";

    try (java.sql.Connection con = util.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, customerIdValue);
        pst.setString(2, petName);
        pst.setString(3, species);
        pst.setString(4, breed);
        pst.setInt(5, ageValue);

        if (pst.executeUpdate() > 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Pet added successfully!");

            txtPetID.setText("");
            txtCustomerID.setText("");
            jlabel3.setText("");
            txtSpecies.setText("");
            txtBreed.setText("");
            txtAge.setText("");
        }
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Customer ID and Age must be numbers.");

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
      String petId = txtPetID.getText().trim();
String customerId = txtCustomerID.getText().trim();
String petName = jlabel3.getText().trim();
String species = txtSpecies.getText().trim();
String breed = txtBreed.getText().trim();
String ageText = txtAge.getText().trim();

if (petId.isEmpty() || customerId.isEmpty() || petName.isEmpty()
        || species.isEmpty() || breed.isEmpty() || ageText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Please fill all fields.");
    return;
}

try {
    int petIdValue = Integer.parseInt(petId);
    int customerIdValue = Integer.parseInt(customerId);
    int ageValue = Integer.parseInt(ageText);

    String sql = "UPDATE pets SET customer_id=?, pet_name=?, "
            + "species=?, breed=?, age=? WHERE pet_id=?";

    try (java.sql.Connection con = util.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, customerIdValue);
        pst.setString(2, petName);
        pst.setString(3, species);
        pst.setString(4, breed);
        pst.setInt(5, ageValue);
        pst.setInt(6, petIdValue);

        if (pst.executeUpdate() > 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Pet updated successfully!");

            txtPetID.setText("");
            txtCustomerID.setText("");
            jlabel3.setText("");
            txtSpecies.setText("");
            txtBreed.setText("");
            txtAge.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Pet ID not found.");
        }
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Pet ID, Customer ID and Age must be numbers.");

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
     String petId = txtPetID.getText().trim();

if (petId.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Please enter Pet ID.");
    return;
}

int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
        "Are you sure you want to delete this pet?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION);

if (confirm != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

try {
    int petIdValue = Integer.parseInt(petId);

    String sql = "DELETE FROM pets WHERE pet_id=?";

    try (java.sql.Connection con = util.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, petIdValue);

        if (pst.executeUpdate() > 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Pet deleted successfully!");

            txtPetID.setText("");
            txtCustomerID.setText("");
            jlabel3.setText("");
            txtSpecies.setText("");
            txtBreed.setText("");
            txtAge.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Pet ID not found.");
        }
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Pet ID must be a number.");

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnDeleteActionPerformed

