    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
      String petId = txtPetID.getText().trim();
String paymentDate = txtPaymentDate.getText().trim();
String amountText = txtAmount.getText().trim();
String paymentMethod = txtPaymentMethod.getText().trim();

if (petId.isEmpty() || paymentDate.isEmpty()
        || amountText.isEmpty() || paymentMethod.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Please fill all fields.");
    return;
}

try {
    int petIdValue = Integer.parseInt(petId);

    java.sql.Date dateValue =
            java.sql.Date.valueOf(paymentDate);

    double amountValue =
            Double.parseDouble(amountText);

    String sql = "INSERT INTO payments "
            + "(pet_id, payment_date, amount, payment_method) "
            + "VALUES (?, ?, ?, ?)";

    try (java.sql.Connection con =
            util.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst =
            con.prepareStatement(sql)) {

        pst.setInt(1, petIdValue);
        pst.setDate(2, dateValue);
        pst.setDouble(3, amountValue);
        pst.setString(4, paymentMethod);

        if (pst.executeUpdate() > 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Payment added successfully!");

            txtPaymentID.setText("");
            txtPetID.setText("");
            txtPaymentDate.setText("");
            txtAmount.setText("");
            txtPaymentMethod.setText("");
        }
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Pet ID and Amount must be numbers.");

} catch (IllegalArgumentException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Date must be in YYYY-MM-DD format.");

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
      String paymentId = txtPaymentID.getText().trim();
String petId = txtPetID.getText().trim();
String paymentDate = txtPaymentDate.getText().trim();
String amountText = txtAmount.getText().trim();
String paymentMethod = txtPaymentMethod.getText().trim();

if (paymentId.isEmpty() || petId.isEmpty()
        || paymentDate.isEmpty() || amountText.isEmpty()
        || paymentMethod.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Please fill all fields.");
    return;
}

try {
    int paymentIdValue = Integer.parseInt(paymentId);
    int petIdValue = Integer.parseInt(petId);

    java.sql.Date dateValue =
            java.sql.Date.valueOf(paymentDate);

    double amountValue =
            Double.parseDouble(amountText);

    String sql = "UPDATE payments SET "
            + "pet_id=?, payment_date=?, amount=?, "
            + "payment_method=? WHERE payment_id=?";

    try (java.sql.Connection con =
            util.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst =
            con.prepareStatement(sql)) {

        pst.setInt(1, petIdValue);
        pst.setDate(2, dateValue);
        pst.setDouble(3, amountValue);
        pst.setString(4, paymentMethod);
        pst.setInt(5, paymentIdValue);

        if (pst.executeUpdate() > 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Payment updated successfully!");

            txtPaymentID.setText("");
            txtPetID.setText("");
            txtPaymentDate.setText("");
            txtAmount.setText("");
            txtPaymentMethod.setText("");

        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Payment ID not found.");
        }
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Payment ID, Pet ID and Amount must be numbers.");

} catch (IllegalArgumentException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Date must be in YYYY-MM-DD format.");

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String paymentId = txtPaymentID.getText().trim();

if (paymentId.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Please enter Payment ID.");
    return;
}

int confirm = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this payment?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirm != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

try {
    int paymentIdValue = Integer.parseInt(paymentId);

    String sql = "DELETE FROM payments WHERE payment_id=?";

    try (java.sql.Connection con = util.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, paymentIdValue);

        if (pst.executeUpdate() > 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Payment deleted successfully!");

            txtPaymentID.setText("");
            txtPetID.setText("");
            txtPaymentDate.setText("");
            txtAmount.setText("");
            txtPaymentMethod.setText("");

        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Payment ID not found.");
        }
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Payment ID must be a number.");

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnDeleteActionPerformed

